"""Fill in the server types of ``tests/fixtures/pg_common_types.toml``.

Each query is prepared, not run, on the server ``SQLTY_PG_DSN`` points to, and the
type of its single column replaces the one in the file::

    SQLTY_PG_DSN=postgresql://postgres:postgres@localhost:5432/postgres \\
        uv run --group psycopg python scripts/refresh_pg_types.py
"""

from __future__ import annotations

import json
import os
import sys
import tomllib
from pathlib import Path

import psycopg
from psycopg import pq

FIXTURE = Path(__file__).parent.parent / "tests" / "fixtures" / "pg_common_types.toml"
HEADER = """\
# The type PostgreSQL {version} gives each query's single column, as pg_type.typname.
# Generated by scripts/refresh_pg_types.py; add a query with any type, then run it.
"""


def main() -> int:
    dsn = os.environ.get("SQLTY_PG_DSN")
    if not dsn:
        print("SQLTY_PG_DSN is not set", file=sys.stderr)
        return 2
    sections: dict[str, dict[str, str]] = tomllib.loads(FIXTURE.read_text())
    with psycopg.connect(dsn, autocommit=True) as conn:
        version = conn.execute("SHOW server_version").fetchone()
        typnames = type_names(conn)
        out = [HEADER.format(version=version[0].split()[0] if version else "?")]
        for section, queries in sections.items():
            out.append(f"\n[{section}]\n")
            for query in queries:
                out.append(f"{json.dumps(query)} = {json.dumps(typnames[describe(conn, query)])}\n")
    FIXTURE.write_text("".join(out))
    return 0


def type_names(conn: psycopg.Connection) -> dict[int, str]:
    """``pg_type.typname`` by OID, ``int4[]`` for an array of ``int4``."""
    rows = conn.execute(
        "SELECT t.oid, CASE WHEN e.oid IS NULL THEN t.typname ELSE e.typname || '[]' END"
        " FROM pg_type t LEFT JOIN pg_type e ON e.oid = t.typelem AND t.typcategory = 'A'"
    ).fetchall()
    return dict(rows)


def describe(conn: psycopg.Connection, query: str) -> int:
    """The type OID of the single column of ``query``, which is prepared, not run."""
    pgconn = conn.pgconn
    result = pgconn.prepare(b"sqlty_refresh", query.encode())
    if result.status != pq.ExecStatus.COMMAND_OK:
        raise SystemExit(f"{query}: {result.error_message.decode(errors='replace').strip()}")
    try:
        description = pgconn.describe_prepared(b"sqlty_refresh")
        if description.nfields != 1:
            raise SystemExit(f"{query}: {description.nfields} columns, expected 1")
        return description.ftype(0)
    finally:
        pgconn.exec_(b"DEALLOCATE sqlty_refresh")


if __name__ == "__main__":
    raise SystemExit(main())
