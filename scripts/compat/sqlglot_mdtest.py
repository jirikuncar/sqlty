"""Write the sqlglot rows that match the server as mdtests.

Reads `reports/sqlglot.json` (from `run.py sqlglot` with a server) and writes, per
dialect, `tests/mdtest/<dialect>/sqlglot_expressions.md`: the rows whose sqlty type
matched the value the reference driver returned. Fill in the assertions with
`uv run pytest --update-mdtest tests/mdtest/<dialect>/sqlglot_expressions.md`.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).parent.parent.parent
HEADER = """# sqlglot expression corpus

Expressions from sqlglot {version}'s `{files}`, over its table `tbl`, whose sqlty
type matched the type of the value {driver} returned from a live {server}. Generated by
`scripts/compat/sqlglot_mdtest.py`; see `scripts/compat/reports/sqlglot.md`.

`schema.sql`:

```sql
{schema}
```

```toml
[tool.sqlty]
dialect = "{dialect}"
schema = "schema.sql"
```
"""
SERVERS = {"postgres": ("psycopg", "PostgreSQL 17"), "mysql": ("PyMySQL", "MySQL 9.2")}


def main() -> None:
    results = json.loads((Path(__file__).parent / "reports" / "sqlglot.json").read_text())
    for dialect, (driver, server) in SERVERS.items():
        rows = [
            r["row"]
            for r in results
            if r["row"]["dialect"] == dialect
            and r["outcome"] == "match"
            and ", server " in r["row"]["provenance"]
        ]
        if not rows:
            continue
        files = sorted({r["provenance"].split(":")[0] for r in rows})
        text = HEADER.format(
            version=rows[0]["version"],
            files="`, `".join(files),
            driver=driver,
            server=server,
            schema=rows[0]["schema"],
            dialect=dialect,
        )
        for row in rows:
            text += f"\n```sql\nSELECT {row['sql']} AS x FROM tbl\n-- columns:\n```\n"
        (ROOT / "tests" / "mdtest" / dialect / "sqlglot_expressions.md").write_text(text)


if __name__ == "__main__":
    main()
