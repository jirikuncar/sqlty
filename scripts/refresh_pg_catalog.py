"""Write ``pg_catalog_views.sql``: the views and hash functions of ``pg_catalog``.

The columns and signatures are read from the server ``SQLTY_PG_DSN`` points to::

    SQLTY_PG_DSN=postgresql://postgres:postgres@localhost:5432/postgres \\
        uv run --group psycopg python scripts/refresh_pg_catalog.py

A view column has no ``NOT NULL`` in the catalog, so every column is nullable.
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

import psycopg

OUT = Path(__file__).parent.parent / "rust/crates/sqlty-sql/src/catalog/pg_catalog_views.sql"
HEADER = """\
-- The views and hash functions of pg_catalog in PostgreSQL {version}.
-- Generated by scripts/refresh_pg_catalog.py; do not edit.
"""
VIEWS = """
SELECT quote_ident(c.relname),
       string_agg(quote_ident(a.attname) || ' ' || format_type(a.atttypid, a.atttypmod), ', '
                  ORDER BY a.attnum)
FROM pg_class c
JOIN pg_namespace n ON n.oid = c.relnamespace
JOIN pg_attribute a ON a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped
WHERE n.nspname = 'pg_catalog' AND c.relkind = 'v'
GROUP BY c.relname
ORDER BY c.relname
"""
# The hash support functions: undocumented, but called directly to bucket or shard rows.
FUNCTIONS = """
SELECT quote_ident(p.proname), pg_get_function_identity_arguments(p.oid),
       format_type(p.prorettype, NULL), p.proisstrict
FROM pg_proc p
JOIN pg_namespace n ON n.oid = p.pronamespace
WHERE n.nspname = 'pg_catalog' AND p.proname ~ '^hash' AND NOT p.proretset
  AND p.prorettype IN ('int4'::regtype, 'int8'::regtype)
  AND NOT 'internal'::regtype = ANY (p.proargtypes::oid[])
ORDER BY p.proname, p.oid
"""


def main() -> int:
    dsn = os.environ.get("SQLTY_PG_DSN")
    if not dsn:
        print("SQLTY_PG_DSN is not set", file=sys.stderr)
        return 2
    with psycopg.connect(dsn, autocommit=True) as conn:
        version = conn.execute("SHOW server_version").fetchone()
        out = [HEADER.format(version=version[0].split()[0] if version else "?")]
        for name, columns in conn.execute(VIEWS):
            out.append(f"CREATE TABLE pg_catalog.{name} ({columns});\n")
        for name, args, returns, strict in conn.execute(FUNCTIONS):
            out.append(
                f"CREATE FUNCTION pg_catalog.{name}({args}) RETURNS {returns}"
                f" LANGUAGE internal{' STRICT' if strict else ''} AS '{name}';\n"
            )
    OUT.write_text("".join(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
