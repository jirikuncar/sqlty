"""Tests for preserving unrelated code in stub files during generation."""

from pathlib import Path

from sqlty._generator import TypeStubGenerator


def test_preserve_custom_imports_in_incremental_mode(tmp_path: Path) -> None:
    """Incremental mode should preserve custom imports not added by the tool."""
    stub_path = tmp_path / "queries.pyi"

    # Create stub with custom imports and helper functions
    stub_path.write_text("""from typing import overload, Literal
from sqlty import SQL, SQLRegistry
from datetime import datetime
from myapp.types import UserId


class Query(SQLRegistry):
    @overload
    @classmethod
    def sql(
        cls,
        query: Literal["SELECT 1"],
    ) -> SQL[tuple[int]]: ...

    @overload
    @classmethod
    def sql[T](cls, query: T) -> T: ...


# Type alias for the sql function
sql = Query.sql
""")

    source_file = tmp_path / "queries.py"
    source_file.write_text("""
from sqlty import SQLRegistry

class Query(SQLRegistry):
    pass

query1 = Query.sql("SELECT 1")
query2 = Query.sql("SELECT 2")
""")

    generator = TypeStubGenerator()
    generator.generate_stub_file(source_file, output_path=stub_path, mode="incremental")

    content = stub_path.read_text()

    # Should preserve custom imports
    assert "from datetime import datetime" in content
    assert "from myapp.types import UserId" in content

    # Should have both queries
    assert "SELECT 1" in content
    assert "SELECT 2" in content


def test_preserve_custom_classes_and_functions(tmp_path: Path) -> None:
    """Full mode should preserve custom classes and functions outside the Query class."""
    stub_path = tmp_path / "queries.pyi"

    # Create stub with custom helper classes and functions
    stub_path.write_text("""from typing import overload, Literal
from sqlty import SQL, SQLRegistry


# Custom helper type
class DatabaseRow:
    id: int
    name: str


def format_query(query: str) -> str:
    '''Helper function to format queries.'''
    return query.strip()


class Query(SQLRegistry):
    @overload
    @classmethod
    def sql(
        cls,
        query: Literal["SELECT 1"],
    ) -> SQL[tuple[int]]: ...

    @overload
    @classmethod
    def sql[T](cls, query: T) -> T: ...


# Type alias for the sql function
sql = Query.sql


# Another custom function
def validate_query(query: str) -> bool:
    return len(query) > 0
""")

    source_file = tmp_path / "queries.py"
    source_file.write_text("""
from sqlty import SQLRegistry

class Query(SQLRegistry):
    pass


query1 = Query.sql("SELECT 1")
query2 = Query.sql("SELECT 2")
""")

    generator = TypeStubGenerator()
    generator.generate_stub_file(source_file, output_path=stub_path, mode="full")

    content = stub_path.read_text()

    # Should preserve custom classes
    assert "class DatabaseRow:" in content
    assert "id: int" in content
    assert "name: str" in content

    # Should preserve custom functions
    assert "def format_query(query: str) -> str:" in content
    assert "def validate_query(query: str) -> bool:" in content

    # Should have updated the Query class with new queries
    assert "SELECT 1" in content
    assert "SELECT 2" in content


