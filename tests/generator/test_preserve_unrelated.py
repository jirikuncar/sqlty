def test_preserve_multiple_classes(tmp_path: Path) -> None:
    """Should preserve other classes in the stub file."""
    stub_path = tmp_path / "queries.pyi"

    stub_path.write_text("""from typing import overload, Literal
from sqlty import SQL, SQLRegistry


class UserQueries(SQLRegistry):
    @overload
    @classmethod
    def user_sql(
        cls,
        query: Literal["SELECT * FROM users"],
    ) -> SQL[tuple[int, str]]: ...

    @overload
    @classmethod
    def user_sql[T](cls, query: T) -> T: ...


class Query(SQLRegistry):
    @overload
    @classmethod
    def sql(
        cls,
        query: Literal["SELECT 1"],
    ) -> SQL[tuple[int]]: ...

    @overload
    @classmethod
    def sql[T](cls, query: T) -> T: ...


# Type aliases
user_sql = UserQueries.user_sql
sql = Query.sql
""")

    source_file = tmp_path / "queries.py"
    source_file.write_text("""
from sqlty import SQLRegistry

class Query(SQLRegistry):
    pass

query1 = Query.sql("SELECT 1")
query2 = Query.sql("SELECT 2")
""")

    generator = TypeStubGenerator()
    generator.generate_stub_file(source_file, output_path=stub_path, mode="full")

    content = stub_path.read_text()

    # Should preserve the UserQueries class
    assert "class UserQueries(SQLRegistry):" in content
    assert "def user_sql(" in content
    assert "SELECT * FROM users" in content

    # Should update the Query class
    assert "SELECT 1" in content
    assert "SELECT 2" in content

    # Should preserve type aliases
    assert "user_sql = UserQueries.user_sql" in content
    assert "sql = Query.sql" in content


