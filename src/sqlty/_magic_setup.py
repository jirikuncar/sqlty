#!/usr/bin/env python3
"""Install sitecustomize.py to enable magic codec globally.

This script creates a sitecustomize.py file in your Python's site-packages
directory that automatically imports sqlty.magic on Python startup.
"""

import site
import sys
from pathlib import Path


def install_sitecustomize():
    """Install sitecustomize.py to enable sqlty magic codec."""
    # Get site-packages directories
    site_packages = site.getsitepackages()

    if not site_packages:
        print("Error: Could not find site-packages directory")
        return False

    # Use the first writable site-packages
    target_dir = None
    for sp in site_packages:
        sp_path = Path(sp)
        if sp_path.exists() and sp_path.is_dir():
            try:
                # Test if writable
                test_file = sp_path / ".write_test"
                test_file.touch()
                test_file.unlink()
                target_dir = sp_path
                break
            except (PermissionError, OSError):
                continue

    if not target_dir:
        print("Error: No writable site-packages directory found")
        print("You may need to run with sudo/admin privileges")
        print(f"Tried: {site_packages}")
        return False

    sitecustomize_path = target_dir / "sitecustomize.py"

    # Check if sitecustomize.py already exists
    if sitecustomize_path.exists():
        content = sitecustomize_path.read_text()
        if "sqlty.magic" in content:
            print(f"✓ sqlty.magic already configured in {sitecustomize_path}")
            return True

        # Append to existing file
        print(f"Found existing {sitecustomize_path}, appending...")
        with sitecustomize_path.open("a") as f:
            f.write("\n# SQLTy magic codec\n")
            f.write("try:\n")
            f.write("    import sqlty.magic\n")
            f.write("except ImportError:\n")
            f.write("    pass  # sqlty not installed\n")
    else:
        # Create new file
        sitecustomize_path.write_text("""# Auto-generated by sqlty
# This file enables sqlty magic codec globally

try:
    import sqlty.magic
except ImportError:
    pass  # sqlty not installed
""")

    print(f"✓ Installed sitecustomize.py to {sitecustomize_path}")
    print("\nThe magic codec is now enabled globally!")
    print("You can use --sql strings without encoding declarations:")
    print('  q = "--sql SELECT 1::INTEGER"')
    print("  # Transforms to: SQL[tuple[int]](...)")
    return True


def uninstall_sitecustomize():
    """Remove sqlty.magic from sitecustomize.py."""
    site_packages = site.getsitepackages()

    for sp in site_packages:
        sp_path = Path(sp)
        sitecustomize_path = sp_path / "sitecustomize.py"

        if sitecustomize_path.exists():
            content = sitecustomize_path.read_text()
            if "sqlty.magic" not in content:
                continue

            # Remove sqlty.magic lines
            lines = content.splitlines()
            new_lines = []
            skip_next = 0

            for line in lines:
                if skip_next > 0:
                    skip_next -= 1
                    continue
                if "sqlty" in line.lower() and "magic" in line.lower():
                    # Skip this line and possibly next few
                    if "try:" in lines[max(0, lines.index(line) - 1)]:
                        skip_next = 2  # Skip except and pass
                    continue
                new_lines.append(line)

            if new_lines:
                sitecustomize_path.write_text("\n".join(new_lines) + "\n")
                print(f"✓ Removed sqlty.magic from {sitecustomize_path}")
            else:
                sitecustomize_path.unlink()
                print(f"✓ Removed {sitecustomize_path}")

            return True

    print("No sitecustomize.py with sqlty.magic found")
    return False


def main():
    """Main entry point."""
    import argparse

    parser = argparse.ArgumentParser(
        description="Install or uninstall sqlty magic codec globally"
    )
    parser.add_argument(
        "action",
        choices=["install", "uninstall", "status"],
        help="Action to perform"
    )

    args = parser.parse_args()

    if args.action == "install":
        success = install_sitecustomize()
        sys.exit(0 if success else 1)
    elif args.action == "uninstall":
        success = uninstall_sitecustomize()
        sys.exit(0 if success else 1)
    elif args.action == "status":
        # Check if sqlty.magic is in any sitecustomize.py
        site_packages = site.getsitepackages()
        found = False

        for sp in site_packages:
            sp_path = Path(sp)
            sitecustomize_path = sp_path / "sitecustomize.py"

            if sitecustomize_path.exists():
                content = sitecustomize_path.read_text()
                if "sqlty.magic" in content:
                    print(f"✓ Magic codec enabled in {sitecustomize_path}")
                    found = True

        if not found:
            print("✗ Magic codec not installed globally")
            print("Run 'python -m sqlty.magic install' to enable it")

        sys.exit(0 if found else 1)


if __name__ == "__main__":
    main()
